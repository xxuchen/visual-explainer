#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateDesign } from './model.mjs';
import { verifyEvidence, recordEvidence } from './evidence.mjs';
import { renderDesignSource } from './render.mjs';
import { renderWithUpstream } from './upstream.mjs';
import { inspectHtml, inspectBrowser } from './inspect.mjs';

const usage = `Software design profile (Node >=20)
  init <design.json>
  validate <design.json> [--phase design|delivery]
  render <design.json> --out <page.html> [--phase design|delivery] [--browser | --require-browser] [--browser-executable <path>]
  inspect <page.html> [--spec <design.json>] [--browser | --require-browser] [--browser-executable <path>]
  record <design.json> --acceptance AC-id --receipt evidence/run.json [--cwd <dir>] [--timeout-ms <n>] -- <executable> <args...>
Paths for receipt and its log are relative to the design JSON. record never edits that JSON.
Browser unavailable: skipped (exit 0 with --browser, exit 1 with --require-browser).
Business acceptance, model validation, and HTML checks are reported separately.`;

function parse(args) {
  const command = args.shift();
  if (!command || ['help', '--help', '-h'].includes(command)) return { help: true };
  if (!['init', 'validate', 'render', 'inspect', 'record'].includes(command)) throw new Error(`Unknown command: ${command}`);
  const input = args.shift();
  if (!input || input.startsWith('--')) throw new Error('A source file path is required.');
  const allowed = { init: [], validate: ['phase'], render: ['out', 'phase', 'browser', 'require-browser', 'browser-executable'], inspect: ['spec', 'browser', 'require-browser', 'browser-executable'], record: ['acceptance', 'receipt', 'cwd', 'timeout-ms'] }[command];
  const flags = {};
  let argv = [];
  while (args.length) {
    const arg = args.shift();
    if (arg === '--' && command === 'record') { argv = args; break; }
    if (!arg.startsWith('--') || !allowed.includes(arg.slice(2))) throw new Error(`Unexpected option for ${command}: ${arg}`);
    const key = arg.slice(2);
    if (Object.hasOwn(flags, key)) throw new Error(`Repeated option: ${arg}`);
    if (['browser', 'require-browser'].includes(key)) flags[key] = true;
    else { const value = args.shift(); if (!value || value.startsWith('--')) throw new Error(`Missing value for ${arg}`); flags[key] = value; }
  }
  if (flags.phase && !['design', 'delivery'].includes(flags.phase)) throw new Error('phase must be design or delivery.');
  if (command === 'render' && !flags.out) throw new Error('render requires --out <page.html>.');
  if (command === 'record' && (!flags.acceptance || !flags.receipt || !argv.length)) throw new Error('record requires --acceptance, --receipt and an executable after --.');
  return { command, input: resolve(input), flags, argv };
}

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));
const emit = (result) => console.log(JSON.stringify(result, null, 2));
const digest = (text) => createHash('sha256').update(text).digest('hex');
function validationFor(spec, input, phase) {
  const evidence = verifyEvidence(spec, dirname(input));
  return { ...validateDesign(spec, { phase, evidence }), phase, evidence: Object.fromEntries(evidence) };
}
function writeGenerated(path, data, marker) {
  if (existsSync(path)) {
    const existing = readFileSync(path, 'utf8');
    if (!existing.includes(marker)) throw new Error(`Refusing to overwrite a file not generated by this profile: ${path}`);
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, data);
}
async function browserCheck(path, flags) {
  if (!flags.browser && !flags['require-browser']) return { status: 'not-run', errors: [], reason: 'Browser inspection was not requested.' };
  return inspectBrowser(path, { required: Boolean(flags['require-browser']), executablePath: flags['browser-executable'], artifactDir: `${path}.screenshots` });
}
const browserOK = (result, flags) => result.status !== 'failed' && (!flags['require-browser'] || result.status === 'passed');

export async function main(args = process.argv.slice(2)) {
  const opts = parse([...args]);
  if (opts.help) { console.log(usage); return 0; }
  const { command, input, flags, argv } = opts;
  if (command === 'init') {
    const example = readFileSync(new URL('../templates/software-design.json', import.meta.url), 'utf8');
    mkdirSync(dirname(input), { recursive: true });
    writeFileSync(input, example, { flag: 'wx' });
    emit({ profile: 'software-design/v1', status: 'created', path: input, next: 'Replace example requirements and assumptions with project evidence before rendering.' });
    return 0;
  }
  if (command === 'inspect') {
    const html = readFileSync(input, 'utf8');
    const spec = flags.spec ? readJson(resolve(flags.spec)) : undefined;
    const staticCheck = inspectHtml(html, { spec });
    const browser = staticCheck.ok ? await browserCheck(input, flags) : { status: 'not-run', errors: [], reason: 'Static inspection failed.' };
    const ok = staticCheck.ok && browserOK(browser, flags);
    emit({ profile: 'software-design/v1', ok, static: { status: staticCheck.ok ? 'passed' : 'failed', ...staticCheck }, browser, htmlSha256: digest(html) });
    return ok ? 0 : 1;
  }
  const spec = readJson(input);
  if (command === 'record') {
    // Commands are explicit CLI argv. They are never sourced from the document or HTML.
    const receipt = recordEvidence(spec, dirname(input), { acceptanceId: flags.acceptance, receipt: flags.receipt, command: argv, cwd: flags.cwd ? resolve(flags.cwd) : dirname(input), timeoutMs: flags['timeout-ms'] === undefined ? 120000 : Number(flags['timeout-ms']) });
    emit({ profile: 'software-design/v1', ...receipt, next: `Set ${flags.acceptance}.verification to ${JSON.stringify({ status: receipt.status, receipt: flags.receipt })} after reviewing the log.` });
    return receipt.status === 'passed' ? 0 : 1;
  }
  const phase = flags.phase ?? 'design';
  const validation = validationFor(spec, input, phase);
  if (command === 'validate' || !validation.ok) { emit(validation); return validation.ok ? 0 : 1; }
  const out = resolve(flags.out);
  if (!/\.html?$/i.test(out)) throw new Error('--out must name an HTML file.');
  if (out === input || (existsSync(out) && realpathSync(out) === realpathSync(input))) throw new Error('HTML output must differ from the JSON source.');
  const checksPath = `${out}.checks.json`;
  validation.pageChecks = { static: { status: 'not-run' }, browser: { status: 'not-run' } };
  const makePage = () => renderWithUpstream(renderDesignSource(spec, validation));
  let html = makePage();
  let staticCheck = inspectHtml(html, { spec });
  if (!staticCheck.ok) { emit({ profile: 'software-design/v1', ok: false, validation, static: staticCheck }); return 1; }
  validation.pageChecks.static = { status: 'passed' };
  html = makePage();
  writeGenerated(out, html, 'data-sd-profile="1"');
  let browser = await browserCheck(out, flags);
  validation.pageChecks.browser = browser;
  html = makePage();
  staticCheck = inspectHtml(html, { spec });
  if (!staticCheck.ok) { emit({ profile: 'software-design/v1', ok: false, static: staticCheck }); return 1; }
  writeGenerated(out, html, 'data-sd-profile="1"');
  // If a browser was available, verify the final page including its displayed check results.
  if (browser.status === 'passed') {
    browser = await browserCheck(out, flags);
    if (browser.status !== 'passed') {
      validation.pageChecks.browser = browser;
      html = makePage();
      writeGenerated(out, html, 'data-sd-profile="1"');
      staticCheck = inspectHtml(html, { spec });
    }
  }
  const ok = validation.ok && staticCheck.ok && browserOK(browser, flags);
  const report = { profile: 'software-design/v1', ok, phase, source: input, output: out, htmlSha256: digest(html),
    design: { status: validation.ok ? 'passed' : 'failed', errors: validation.errors, warnings: validation.warnings },
    business: Object.fromEntries((spec.acceptance ?? []).map((a) => [a.id, a.verification.status])),
    static: { status: staticCheck.ok ? 'passed' : 'failed', ...staticCheck }, browser };
  writeGenerated(checksPath, `${JSON.stringify(report, null, 2)}\n`, '"profile": "software-design/v1"');
  emit({ ...report, checksPath });
  return ok ? 0 : 1;
}

let direct = false;
try { direct = Boolean(process.argv[1]) && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url)); } catch {}
if (direct) {
  try { process.exitCode = await main(); } catch (error) { console.error(`Software design: ${error.message}`); process.exitCode = 1; }
}
